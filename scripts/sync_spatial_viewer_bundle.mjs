#!/usr/bin/env node
/**
 * Keeps the Node's embedded Spatial viewer identical to the art.kubus one.
 *
 * The viewer's source of truth is `assets/spatial_viewer/src/viewer.js` in the
 * art.kubus repository, built there with `npm ci && npm run build`. This script
 * does not build anything: it wraps that repository's `viewer.bundle.js`,
 * byte for byte, into `src/gui/public/vendor/spatialViewerBundle.ts`, and
 * records the hashes that tie the copy to its source.
 *
 *   node scripts/sync_spatial_viewer_bundle.mjs --app ../art.kubus          write
 *   node scripts/sync_spatial_viewer_bundle.mjs --app ../art.kubus --check  verify, change nothing
 *
 * `--check` exits non-zero if the Node copy differs from the app's bundle, or
 * if the app's bundle is not what its own source and lockfile build to (the
 * latter needs `npm ci` to have been run there; it is skipped otherwise and
 * says so).
 */
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const target = path.resolve(here, '../src/gui/public/vendor/spatialViewerBundle.ts');
const args = process.argv.slice(2);
const flag = (name) => args.includes(name);
const option = (name) => { const index = args.indexOf(name); return index >= 0 ? args[index + 1] : undefined; };
const sha256 = (value) => createHash('sha256').update(value).digest('hex');

const appRoot = path.resolve(option('--app') ?? process.env.KUBUS_ART_KUBUS_DIR ?? '');
const viewerDirectory = path.join(appRoot, 'assets', 'spatial_viewer');
if (!option('--app') && !process.env.KUBUS_ART_KUBUS_DIR) {
  console.error('Pass --app <path to the art.kubus checkout> (or set KUBUS_ART_KUBUS_DIR).');
  process.exit(2);
}
const bundlePath = path.join(viewerDirectory, 'viewer.bundle.js');
const sourcePath = path.join(viewerDirectory, 'src', 'viewer.js');
const packagePath = path.join(viewerDirectory, 'package.json');
for (const file of [bundlePath, sourcePath, packagePath]) {
  if (!existsSync(file)) { console.error(`Missing ${file}`); process.exit(2); }
}

const bundle = readFileSync(bundlePath, 'utf8');
const pins = JSON.parse(readFileSync(packagePath, 'utf8'));
const provenance = {
  repository: 'kubus-project/art.kubus',
  sourcePath: 'assets/spatial_viewer/src/viewer.js',
  sourceSha256: sha256(readFileSync(sourcePath)),
  bundleSha256: sha256(bundle),
  spark: pins.dependencies['@sparkjsdev/spark'],
  three: pins.dependencies.three,
  esbuild: pins.devDependencies.esbuild,
};

const header = `/**
 * Pre-built Three.js + Spark (@sparkjsdev/spark) Gaussian-splat viewer.
 *
 * Generated by \`scripts/sync_spatial_viewer_bundle.mjs\` from the art.kubus
 * repository's \`assets/spatial_viewer/viewer.bundle.js\` - copied verbatim, never
 * rebuilt or edited here, so the Node and the app run the very same rendering
 * code rather than two drifting ones. The viewer's source is
 * \`assets/spatial_viewer/src/viewer.js\` there; change it there and run the
 * script. \`spatialViewerBundleSource\` records which source and build this is,
 * and \`tests/spatialViewerBundle.test.ts\` fails if the two disagree.
 *
 * Self-contained: no CDN, no network fetch for the library itself.
 *
 * Page API (window): loadSpatial(url) opens one splat file;
 * loadSpatialProgressive({ preview, runtime }) draws a small preview first and
 * swaps in a paged runtime tree when it can draw; unloadSpatial() releases the
 * scene; spatialViewerState() reports the stage; resetSpatialView().
 */
`;
const output = `${header}export const spatialViewerBundleSource = ${JSON.stringify(provenance, null, 2)} as const;\n\nexport const spatialViewerBundle = ${JSON.stringify(bundle)};\n`;

if (flag('--check')) {
  let failed = false;
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (current !== output) { console.error('The Node viewer bundle differs from the art.kubus bundle (or its recorded provenance is stale).'); failed = true; }

  if (existsSync(path.join(viewerDirectory, 'node_modules', '.bin', 'esbuild'))) {
    const scratch = mkdtempSync(path.join(tmpdir(), 'kubus-viewer-'));
    try {
      const built = path.join(scratch, 'viewer.bundle.js');
      const run = spawnSync(path.join(viewerDirectory, 'node_modules', '.bin', 'esbuild'), ['src/viewer.js', '--bundle', '--minify', '--format=iife', `--outfile=${built}`, '--log-level=error'], { cwd: viewerDirectory, encoding: 'utf8' });
      if (run.status !== 0) { console.error(`Rebuilding the viewer failed: ${run.stderr}`); failed = true; }
      else if (sha256(readFileSync(built)) !== provenance.bundleSha256) { console.error('The app\'s committed bundle is not what its source and lockfile build to.'); failed = true; }
      else console.log('The app bundle reproduces from its source.');
    } finally { rmSync(scratch, { recursive: true, force: true }); }
  } else {
    console.log('Reproducibility of the app bundle not checked: run `npm ci` in assets/spatial_viewer first.');
  }
  if (failed) process.exit(1);
  console.log(`Node viewer bundle matches the app (${provenance.bundleSha256.slice(0, 12)}).`);
} else {
  writeFileSync(target, output);
  console.log(`Wrote ${path.relative(process.cwd(), target)} (${bundle.length} bytes, sha256 ${provenance.bundleSha256.slice(0, 12)}).`);
}
